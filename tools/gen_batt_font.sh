# Regenerate firmware-idf/main/font_batt.c: the digits printed INSIDE the
# battery icon on the T-Display layout (layout_tdisplay.c).
#
# WHY BOLD 12 px: the icon's interior is 23x10 px. Montserrat Bold at 12 px
# gives 9 px-tall digits and "100" = 21 px wide, so three digits fit with a
# pixel to spare. The built-in Montserrat 14 is regular weight and its "100"
# is 24 px — too wide, and too thin to read through the coloured fill.
#
# The TTF is fetched from the upstream Montserrat release (SIL OFL 1.1) and
# checked against a pinned hash; only the generated C file is committed.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
out="$here/../firmware-idf/main/font_batt.c"
url="https://raw.githubusercontent.com/JulietaUla/Montserrat/v7.222/fonts/ttf/Montserrat-Bold.ttf"
sha="4e6d93bc38122c371acb8dc0dbefbf2649c235191e1be136bb5720546d719808"

tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
curl -sSfL -o "$tmp/Montserrat-Bold.ttf" "$url"
echo "$sha  $tmp/Montserrat-Bold.ttf" | shasum -a 256 -c - >/dev/null

# Run from the temp dir so the generated header records a relative font path.
(cd "$tmp" && npx --yes lv_font_conv \
    --font Montserrat-Bold.ttf --size 12 --bpp 4 --format lvgl \
    --lv-include lvgl.h -r 0x30-0x39 --no-compress -o font_batt.c)

python3 - "$tmp/font_batt.c" "$out" <<'PY'
import sys
src, dst = sys.argv[1], sys.argv[2]
body = open(src).read()
head = ("// SPDX-License-Identifier: Apache-2.0\n"
        "// GENERATED by tools/gen_batt_font.sh -- do not edit by hand.\n"
        "// Montserrat Bold 12 px, digits only: the number inside the battery icon.\n"
        '#include "sdkconfig.h"\n'
        "#if CONFIG_IDF_TARGET_ESP32S3   // LVGL exists only on the display-capable target\n")
open(dst, "w").write(head + body + "\n#endif\n")
PY
echo "wrote $out"
