#!/usr/bin/env python3
"""Generate main/font_bolt.c — a single-glyph LVGL font carrying a lightning
bolt at U+26A1, drawn INSIDE the battery icon while on USB power (the sense
rail cannot see the cell then, so the icon shows "charging" instead of a
number). Polygon, 4bpp, 8x supersampled; 10x11 px = the icon's interior height."""
import os

# W must stay EVEN: LVGL packs 4bpp glyph rows back to back with no per-row
# padding, so an odd width shears every other row (the packer below pads).
W, H = 10, 11
SS = 8
# classic bolt: flat top, notch, long diagonal to the tip
POLY = [(4.7, 0.0), (9.1, 0.0), (6.4, 4.2), (9.3, 4.2),
        (2.7, 11.0), (4.2, 5.9), (0.9, 5.9)]


def inside(px, py):
    hit = False
    n = len(POLY)
    for i in range(n):
        x1, y1 = POLY[i]
        x2, y2 = POLY[(i + 1) % n]
        if (y1 > py) != (y2 > py):
            xi = x1 + (py - y1) * (x2 - x1) / (y2 - y1)
            if px < xi:
                hit = not hit
    return hit


rows = []
for y in range(H):
    row = []
    for x in range(W):
        hits = sum(1 for sy in range(SS) for sx in range(SS)
                   if inside(x + (sx + .5) / SS, y + (sy + .5) / SS))
        row.append(round(15.0 * hits / (SS * SS)))
    rows.append(row)

data = []
for row in rows:
    for i in range(0, W, 2):
        data.append((row[i] << 4) | (row[i + 1] if i + 1 < W else 0))
bpr = (W + 1) // 2
hexrows = ["    " + ", ".join(f"0x{b:02x}" for b in data[r * bpr:(r + 1) * bpr]) + ","
           for r in range(H)]

C = f"""// SPDX-License-Identifier: Apache-2.0
// Copyright 2026 AIDlink contributors
//
// GENERATED by tools/gen_bolt_font.py: single-glyph LVGL font with a lightning
// bolt at U+26A1, drawn inside the battery icon while on USB power.
// Label text is "\\xE2\\x9A\\xA1".
#include "sdkconfig.h"
#if CONFIG_IDF_TARGET_ESP32S3   // LVGL exists only on the display-capable target
#include "lvgl.h"

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{
{chr(10).join(hexrows)}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
    {{.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}} /* id 0 reserved */,
    {{.bitmap_index = 0, .adv_w = {W * 16}, .box_w = {W}, .box_h = {H}, .ofs_x = 0, .ofs_y = 0}},
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{
        .range_start = 0x26A1, .range_length = 1, .glyph_id_start = 1,
        .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,
        .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY
    }},
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 1,
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
}};

const lv_font_t font_bolt = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {H},
    .base_line = 0,
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -1,
    .underline_thickness = 1,
    .dsc = &font_dsc,
}};
#endif  // CONFIG_IDF_TARGET_ESP32S3
"""
out = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "..", "firmware-idf", "main", "font_bolt.c")
open(os.path.normpath(out), "w").write(C)
for row in rows:
    print("".join(" .:-=+*#%@|"[min(v * 10 // 15, 9)] for v in row))
print(f"wrote {os.path.normpath(out)}")
